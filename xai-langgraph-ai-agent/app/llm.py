"""
Generic function-calling loop shared by the product and catalogue nodes.
Two phases per node call:
  1. Let the model call ONE tool round (retrieve_pdp_context or search_products)
     to ground itself in real data.
  2. Force a final streaming call with a lean JSON schema (message + metadata only).
     The heavy products array is assembled by the formatter_node from the tool_trace,
     not re-generated by the LLM — this is the single biggest latency saving.
"""
from __future__ import annotations

import asyncio
import httpx
import json
import logging
from typing import Any

from fastapi import WebSocket
from openai import AsyncOpenAI
from langsmith.wrappers import wrap_openai

from app.config import settings
from app.schemas import AgentResponse
from app.tools.client import ToolCallError

logger = logging.getLogger("chqme.voice_agent")

_client = wrap_openai(AsyncOpenAI(api_key=settings.openai_api_key, timeout=15.0))

# ---------------------------------------------------------------------------
# Lean response schema — LLM only outputs the spoken answer + metadata.
# Product card data is assembled by formatter_node from the tool_trace.
# ---------------------------------------------------------------------------

_RESPONSE_JSON_SCHEMA = {
    "name": "agent_response",
    "strict": True,
    "schema": {
        "type": "object",
        "properties": {
            "message": {"type": "string"},
            "current_product_id": {
                "type": ["string", "null"],
                "description": "Must be the exact numerical Shopify ID (e.g. '9232380625125'). NEVER output the product's name."
            },
            "question_for_you": {
                "type": "array",
                "items": {"type": "string"},
            },
            "product_ids": {
                "type": "array",
                "items": {"type": "string"},
                "description": "If a catalogue level question, provide all relevant product IDs here."
            },
            "feature_id": {
                "type": ["integer", "null"],
                "description": "If asking about a specific feature, provide its numerical ID here."
            },
            "media_id": {
                "type": ["string", "null"],
                "description": "If asking about a specific media or image, provide its ID here."
            },
            "language": {
                "type": "string",
                "description": "The language code of the language you are answering in (e.g. en-IN, hi-IN, mr-IN)."
            },
            "buying_intent": {
                "type": "object",
                "properties": {
                    "intent": {
                        "type": "string",
                        "enum": ["low", "medium", "high"]
                    },
                    "explanation": {"type": "string"}
                },
                "required": ["intent", "explanation"],
                "additionalProperties": False
            }
        },
        "required": [
            "message", "current_product_id", "question_for_you", "product_ids", "feature_id", "media_id", "language", "buying_intent"
        ],
        "additionalProperties": False,
    },
}


async def run_grounded_turn(
    *,
    system_prompt: str,
    messages: list[dict[str, Any]],
    retrieve_fn: Any,           # the retrieval function to call directly (no LLM round)
    retrieve_kwargs: dict,       # kwargs to pass to retrieve_fn (e.g. query=)
    model: str | None = None,
    websocket: WebSocket | None = None,
    turn_id: str | None = None,
    call_id: str | None = None,
    cart_data: list | None = None,
    default_language: str | None = None,
    last_answers_language: str | None = None,
    conversation_summary: str | None = None,
) -> tuple[AgentResponse, list[dict[str, Any]]]:
    """
    Zero-LLM-round grounded turn:
      1. Directly call retrieve_fn (e.g. retrieve_pdp_context) — no LLM tool selection.
      2. Inject the retrieved context into the conversation as a system message.
      3. Stream the final structured answer (message + metadata only).

    The heavy product card assembly is done by formatter_node from tool_trace.
    """
    model = model or settings.response_model
    trace: list[dict[str, Any]] = []

    # ── Directly call the retrieval function — no LLM round at all ────────
    result = await retrieve_fn(**retrieve_kwargs)
    trace.append({"tool": retrieve_fn.__name__, "args": str(retrieve_kwargs), "result": result})

    # Inject retrieved context as a system-level message for the LLM
    context_str = json.dumps(result, default=str)
    
    system_msgs = [
        {"role": "system", "content": system_prompt},
        {"role": "system", "content": f"[RETRIEVED CONTEXT]\n{context_str}"}
    ]
    
    if default_language or last_answers_language:
        lang_str = f"Default Language: {default_language or 'Not Specified'}\nLast Answer's Language: {last_answers_language or 'None yet'}"
        system_msgs.append({
            "role": "system", 
            "content": f"[LANGUAGE CONTEXT]\n{lang_str}"
        })
    
    if cart_data:
        cart_str = json.dumps(cart_data, default=str)
        system_msgs.append({
            "role": "system", 
            "content": f"[CUSTOMER CART DATA]\n{cart_str}\n\nINSTRUCTION: Personalize your answer based on the customer's cart data if relevant."
        })

    if conversation_summary:
        system_msgs.append({
            "role": "system", 
            "content": f"[CONVERSATION SUMMARY (Older Turns)]\n{conversation_summary}"
        })

    convo: list[dict[str, Any]] = system_msgs + messages

    # ── Stream final lean answer ───────────────────────────────────────────
    import partial_json_parser as pjp

    stream = await _client.chat.completions.create(
        model=model,
        messages=convo
        + [
            {
                "role": "user",
                "content": "Give your final spoken answer now, as the JSON schema requires. "
                "Do not call any more tools.",
            }
        ],
        response_format={"type": "json_schema", "json_schema": _RESPONSE_JSON_SCHEMA},
        stream=True,
        stream_options={"include_usage": True},
    )

    accumulated_json = ""
    last_message_len = 0
    prompt_tokens = 0
    completion_tokens = 0

    async for chunk in stream:
        if getattr(chunk, "usage", None):
            prompt_tokens = chunk.usage.prompt_tokens
            completion_tokens = chunk.usage.completion_tokens

        if not chunk.choices:
            continue
        delta = chunk.choices[0].delta
        if delta.content:
            accumulated_json += delta.content

            try:
                parsed = pjp.loads(accumulated_json)
                if isinstance(parsed, dict) and "message" in parsed:
                    current_msg = parsed["message"]
                    if isinstance(current_msg, str):
                        new_text = current_msg[last_message_len:]
                        if new_text and websocket:
                            stream_payload = {
                                "event": "stream",
                                "chunk": new_text,
                            }
                            if turn_id:
                                stream_payload["turn_id"] = turn_id
                                
                            await websocket.send_json(stream_payload)
                        last_message_len = len(current_msg)
            except Exception:
                pass

    try:
        final_dict = json.loads(accumulated_json)
    except Exception as exc:
        raise ValueError(f"Failed to parse final JSON: {accumulated_json}") from exc

    try:
        final_response = AgentResponse.model_validate(final_dict)
    except Exception as exc:
        raise ValueError(f"Invalid final response schema: {final_dict}") from exc
        
    if call_id and (prompt_tokens > 0 or completion_tokens > 0):
        logger.info(f"Dispatching cost update for {call_id}: {prompt_tokens} prompt, {completion_tokens} completion tokens")
        asyncio.create_task(update_call_cost_api(call_id, prompt_tokens, completion_tokens, model))
    else:
        logger.warning(f"Could not dispatch cost update. call_id: {call_id}, prompt_tokens: {prompt_tokens}, completion_tokens: {completion_tokens}")

    return final_response, trace
    
    
async def update_call_cost_api(call_id: str, prompt_tokens: int, completion_tokens: int, model_name: str):
    """
    Calculate the USD cost of the LLM call and fire an async request to the backend.
    Uses GPT-4o and GPT-4o-mini standard pricing per 1M tokens.
    """
    try:
        cost = 0.0
        if "mini" in model_name.lower():
            # gpt-4o-mini: $0.15 / 1M prompt, $0.60 / 1M completion
            cost = (prompt_tokens / 1_000_000 * 0.15) + (completion_tokens / 1_000_000 * 0.60)
        else:
            # gpt-4o: $5.00 / 1M prompt, $15.00 / 1M completion
            cost = (prompt_tokens / 1_000_000 * 5.0) + (completion_tokens / 1_000_000 * 15.0)
            
        if cost > 0:
            logger.info(f"Calculated cost for {call_id}: ${cost:.6f}")
            async with httpx.AsyncClient(timeout=5.0) as client:
                response = await client.post(
                    "https://smartshop.chqme.com/xai/update_call_cost",
                    json={"ai_call_token": call_id, "cost": cost}
                )
                if response.status_code == 200:
                    logger.info(f"Successfully posted call cost for {call_id}")
                else:
                    logger.warning(f"Failed to post call cost for {call_id}. API responded with status {response.status_code}: {response.text}")
    except Exception as e:
        logger.exception(f"Exception occurred while posting call cost for {call_id}: {e}")




async def _execute_tool(name: str, raw_args: str, tool_functions: dict[str, Any]) -> dict:
    print(f"\n[TOOL CALL] Executing tool: '{name}' with args: {raw_args}\n")
    fn = tool_functions.get(name)
    if fn is None:
        return {"error": f"unknown tool '{name}'"}
    try:
        args = json.loads(raw_args) if raw_args else {}
        return await fn(**args)
    except ToolCallError as exc:
        logger.exception(f"tool_call_failed (ToolCallError) in {name}: {exc}")
        return {"error": "tool_unavailable", "detail": str(exc)}
    except Exception as exc:  # noqa: BLE001
        logger.exception(f"tool_call_failed (Exception) in {name}: {exc}")
        return {"error": "tool_unavailable", "detail": str(exc)}
